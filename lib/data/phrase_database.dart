  static List<Phrase> get allPhrases {
    return categories.expand((c) => c.phrases).toList();
  }

  static List<Phrase> getPhrasesByCategory(String categoryId) {
    try {
      return categories.firstWhere((c) => c.id == categoryId).phrases;
    } catch (_) {
      return [];
    }
  }

  static Phrase? getPhraseById(String id) {
    try {
      return allPhrases.firstWhere((p) => p.id == id);
    } catch (_) {
      return null;
    }
  }

  static List<Phrase> search(String query, {String? categoryId}) {
    final q = query.toLowerCase();
    var phrases = allPhrases;
    if (categoryId != null) {
      phrases = getPhrasesByCategory(categoryId);
    }
    return phrases.where((p) =>
      p.textFr.toLowerCase().contains(q) ||
      p.textTr.toLowerCase().contains(q) ||
      p.textEn.toLowerCase().contains(q) ||
      p.tags.any((t) => t.toLowerCase().contains(q))
    ).toList();
  }

